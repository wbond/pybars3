"""Generate compiler/src/tables.rs from CPython's own str predicates.

pybars' grammar classifies characters with CPython's str methods
(isalpha, isalnum, isdigit, isspace, isprintable, and int() for decimal
digits), and their answers depend on the Unicode database of the interpreter
that runs pybars. This script asks each supported CPython, through uv, and
merges the answers into one table per predicate in which every range carries
the set of Unicode versions it is valid for.

    python3 tools/gen_tables.py           # rewrite compiler/src/tables.rs
    python3 tools/gen_tables.py --check   # fail if the file is not up to date

Each interpreter runs this file with --dump. Requires uv on PATH; uv
downloads the interpreters it does not find.
"""

import argparse
import json
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / 'compiler' / 'src' / 'tables.rs'

#: The CPython minor versions to read, oldest first. Each has a different
#: Unicode database; the index of a version here is its bit in the masks.
PYTHONS = ['3.10', '3.11', '3.12', '3.13', '3.14', '3.15']

PREDICATES = {
    'ALPHA': 'isalpha',
    'ALNUM': 'isalnum',
    'DIGIT': 'isdigit',
    'SPACE': 'isspace',
    'PRINTABLE': 'isprintable',
}

HEADER = """\
// Generated by `tools/gen_tables.py` from the Unicode databases of
{pythons}
// Do not edit.

//! Character classes of CPython's `str` predicates, for every supported
//! Unicode version.
//!
//! Each table is a sorted list of disjoint, inclusive code point ranges. The
//! third field is a bit set of the [`crate::UnicodeVersion`]s in which every
//! code point of the range has the property (bit `i` is the version at index
//! `i` of [`VERSIONS`]).

#![allow(clippy::unreadable_literal)]
"""


def ranges(predicate):
    """The inclusive code point ranges where `predicate` holds."""
    out = []
    start = None
    for cp in range(sys.maxunicode + 2):
        ok = cp <= sys.maxunicode and not 0xD800 <= cp <= 0xDFFF and predicate(chr(cp))
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append([start, cp - 1])
            start = None
    return out


def dump():
    """Print this interpreter's character classes as JSON."""
    import unicodedata

    def is_decimal(c):
        # int() accepts exactly the characters for which str.isdecimal() holds.
        return c.isdecimal()

    tables = {name: ranges(getattr(str, method)) for name, method in PREDICATES.items()}
    tables['DECIMAL'] = ranges(is_decimal)
    for start, end in tables['DECIMAL']:
        # Decimal digits come in runs of ten, from 0 to 9.
        assert (end - start + 1) % 10 == 0, hex(start)
        assert unicodedata.decimal(chr(start)) == 0, hex(start)
        assert all(int(chr(cp)) == (cp - start) % 10 for cp in range(start, end + 1)), hex(start)
    json.dump(
        {
            'python': sys.version.split()[0],
            'unicode': unicodedata.unidata_version,
            'tables': tables,
        },
        sys.stdout,
    )


def read(python):
    """Run --dump under CPython `python`."""
    output = subprocess.run(
        ['uv', 'run', '--no-project', '--python', python, 'python', str(Path(__file__).resolve()), '--dump'],
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    return json.loads(output)


def merge(per_version):
    """One masked range list from the range lists of every version."""
    # Sweep over the boundaries: between two consecutive boundaries every
    # code point has the same mask.
    events = {}
    for bit, version_ranges in enumerate(per_version):
        for start, end in version_ranges:
            events[start] = events.get(start, 0) ^ (1 << bit)
            events[end + 1] = events.get(end + 1, 0) ^ (1 << bit)
    out = []
    mask = 0
    points = sorted(events)
    for index, point in enumerate(points):
        mask ^= events[point]
        if mask and index + 1 < len(points):
            end = points[index + 1] - 1
            if out and out[-1][1] + 1 == point and out[-1][2] == mask:
                out[-1] = (out[-1][0], end, mask)
            else:
                out.append((point, end, mask))
    return out


def render(dumps):
    pythons = '\n'.join(f"//   CPython {'.'.join(d['python'].split('.')[:2])}: Unicode {d['unicode']}" for d in dumps)
    lines = [HEADER.format(pythons=pythons).rstrip('\n'), '']
    lines.append('/// The Unicode versions of the tables, in bit order.')
    lines.append('#[cfg(test)]')
    versions = ', '.join(f'"{d["unicode"]}"' for d in dumps)
    lines.append(f'pub(crate) const VERSIONS: [&str; {len(dumps)}] = [{versions}];')
    lines.append('')
    docs = {
        'ALPHA': "`str.isalpha()`: PyMeta's `letter`.",
        'ALNUM': "`str.isalnum()`: PyMeta's `letterOrDigit` (with `_`) and `\\w`.",
        'DIGIT': "`str.isdigit()`: PyMeta's `digit`.",
        'SPACE': "`str.isspace()`: PyMeta's `spaces` and `\\s`.",
        'PRINTABLE': '`str.isprintable()`: what `repr()` leaves unescaped.',
        'DECIMAL': (
            '`str.isdecimal()`: what `int()` accepts. Every range is made of runs of ten\n'
            "/// digits from 0 to 9, so a digit's value is `(cp - start) % 10`."
        ),
    }
    for name in [*PREDICATES, 'DECIMAL']:
        merged = merge([d['tables'][name] for d in dumps])
        lines.append(f'/// {docs[name]}')
        lines.append('#[rustfmt::skip]')
        lines.append(f'pub(crate) static {name}: [(u32, u32, u8); {len(merged)}] = [')
        lines.extend(f'    (0x{a:X}, 0x{b:X}, 0b{m:0{len(dumps)}b}),' for a, b, m in merged)
        lines.append('];')
        lines.append('')
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--dump', action='store_true', help="print this interpreter's tables as JSON")
    parser.add_argument('--check', action='store_true', help=f'fail if {OUTPUT.relative_to(ROOT)} is stale')
    args = parser.parse_args()
    if args.dump:
        dump()
        return 0
    dumps = [read(python) for python in PYTHONS]
    unicode_versions = [d['unicode'] for d in dumps]
    if len(set(unicode_versions)) != len(unicode_versions):
        raise SystemExit(f'two interpreters share a Unicode version: {unicode_versions}')
    text = render(dumps)
    if args.check:
        if OUTPUT.read_text() != text:
            print(f'{OUTPUT.relative_to(ROOT)} is stale: run python3 tools/gen_tables.py', file=sys.stderr)
            return 1
        print(f'{OUTPUT.relative_to(ROOT)} is up to date')
        return 0
    OUTPUT.write_text(text)
    print(f'wrote {OUTPUT.relative_to(ROOT)}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
